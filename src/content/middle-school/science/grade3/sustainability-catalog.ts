type LessonSpec = {
  key: string;
  title: string;
  description: string;
  goals: [string, string];
  concept: string[];
  problem: string;
  steps: Array<[string, string]>;
  practice: Array<{ prompt: string; answers: string[] }>;
  hint: string;
  summary: [string, string];
  formulas?: string[];
};

const lesson = (spec: LessonSpec): MathLesson => ({
  key: spec.key,
  title: spec.title,
  description: spec.description,
  goals: spec.goals,
  concepts: [
    {
      title: spec.title,
      body: spec.concept,
      ...(spec.formulas ? { formulas: spec.formulas } : {}),
    },
  ],
  example: {
    title: `例題: ${spec.title}`,
    problem: spec.problem,
    steps: spec.steps.map(([expression, note]) => ({ expression, note })),
  },
  practice: {
    title: `練習: ${spec.title}`,
    problem: "資料・模式図・条件を基に、科学的な根拠から判断します。",
    steps: spec.practice,
    hint: spec.hint,
  },
  summary: spec.summary,
});

