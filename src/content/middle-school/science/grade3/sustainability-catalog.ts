export const addMiddleScience3SustainabilityUnits = (areas: MathArea[]): MathArea[] =>
  areas.map((area) => {
    const unit = unitsByArea[area.key];
    if (!unit) return area;
    return {
      ...area,
      description:
        area.key === "energy"
          ? `${area.description} さらに、エネルギー資源と科学技術まで扱います。`
          : area.key === "particles"
            ? `${area.description} さらに、物質・資源の有効利用まで扱います。`
            : area.key === "life"
              ? `${area.description} さらに、生態系と環境保全まで扱います。`
              : `${area.description} さらに、自然災害と持続可能な社会まで扱います。`,
      units: [...area.units, unit],
    };
  });
