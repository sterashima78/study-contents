type LessonSpec = {
  key: string;
  title: string;
  description: string;
  goals: [string, string];
  conceptTitle: string;
  body: string[];
  exampleTitle: string;
  exampleProblem: string;
  exampleSteps: Array<[string, string]>;
  practiceTitle: string;
  practiceProblem: string;
  practiceSteps: Array<{ prompt: string; answers: string[] }>;
  hint: string;
  summary: [string, string];
};

const lesson = (spec: LessonSpec): MathLesson => ({
  key: spec.key,
  title: spec.title,
  description: spec.description,
  goals: spec.goals,
  concepts: [
    {
      title: spec.conceptTitle,
      body: spec.body,
    },
  ],
  example: {
    title: spec.exampleTitle,
    problem: spec.exampleProblem,
    steps: spec.exampleSteps.map(([expression, note]) => ({ expression, note })),
  },
  practice: {
    title: spec.practiceTitle,
    problem: spec.practiceProblem,
    steps: spec.practiceSteps,
    hint: spec.hint,
  },
  summary: spec.summary,
});

